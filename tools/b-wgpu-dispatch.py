"""Generates the run-time switch between Dawn and aurora's own Vulkan backend (aurora/lib/vulkan).

Both implement the WebGPU C API, so one libmain cannot hold both under the same names:
  - Dawn's archive gets its wgpu* functions renamed to dawn_wgpu* (llvm-objcopy --redefine-syms with
    aurora/lib/vulkan/dawn_wgpu_syms.txt, done by aurora/cmake/aurora_vk.cmake),
  - vk_webgpu.cpp is compiled with vkw_rename.h, so its functions are vkw_wgpu*,
  - wgpu_dispatch.cpp defines every wgpu* and calls one or the other (aurora_wgpu_vk, set once
    before the first instance).

Usage: python -I tools/b-wgpu-dispatch.py WEBGPU_H DAWN_ARCHIVE LLVM_NM
Writes aurora/lib/vulkan/{dawn_wgpu_syms.txt, vkw_rename.h, wgpu_dispatch.cpp}.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "aurora", "lib", "vulkan")


def prototypes(header):
    text = open(header, encoding="utf-8").read()
    protos = {}
    for m in re.finditer(r"^WGPU_EXPORT[ \t]+([^\n(;]+?)[ \t]+(wgpu[A-Z]\w*)\(([^;]*?)\)\s*WGPU_FUNCTION_ATTRIBUTE;",
                         text, re.M):
        ret, name, params = m.group(1).strip(), m.group(2), " ".join(m.group(3).split())
        protos[name] = (ret, params)
    return protos


def archive_symbols(archive, nm):
    out = subprocess.run([nm, "--defined-only", archive], capture_output=True, text=True).stdout
    return sorted({l.split()[2] for l in out.splitlines() if re.match(r"^\S+ T wgpu[A-Z]\w*$", l)})


def vkw_defined(source):
    names = set()
    for line in open(source, encoding="utf-8"):
        if re.match(r"^[A-Za-z]", line) and not line.rstrip().endswith(";"):
            m = re.search(r"\b(wgpu[A-Z]\w*)\(", line)
            if m:
                names.add(m.group(1))
    return names


def arg_names(params):
    if params.strip() in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*$", p.strip())
        names.append(m.group(1))
    return names


def main():
    header, archive, nm = sys.argv[1:4]
    protos = prototypes(header)
    dawn = [s for s in archive_symbols(archive, nm) if s in protos]
    vkw = vkw_defined(os.path.join(OUT, "vk_webgpu.cpp"))

    with open(os.path.join(OUT, "dawn_wgpu_syms.txt"), "w", newline="\n") as f:
        for s in dawn:
            f.write(f"{s} dawn_{s}\n")

    with open(os.path.join(OUT, "vkw_rename.h"), "w", newline="\n") as f:
        f.write("// Generated by tools/b-wgpu-dispatch.py: vk_webgpu.cpp's WebGPU functions as vkw_wgpu*.\n#pragma once\n")
        for s in sorted(vkw):
            f.write(f"#define {s} vkw_{s}\n")

    lines = [
        "// Generated by tools/b-wgpu-dispatch.py: every WebGPU C function goes to Dawn (dawn_wgpu*) or to",
        "// aurora's Vulkan backend (vkw_wgpu*), whichever aurora_wgpu_vk chose before the first instance.",
        "#include <dawn/webgpu.h>",
        "",
        "#include <cstdio>",
        "#include <cstdlib>",
        "",
        'extern "C" {',
        "bool aurora_wgpu_vk = false;",
        "",
        "[[noreturn]] static void aurora_wgpu_missing(const char* name) {",
        '  std::fprintf(stderr, "[aurora] the Vulkan backend has no %s\\n", name);',
        "  std::abort();",
        "}",
        "",
    ]
    for s in dawn:
        ret, params = protos[s]
        args = ", ".join(arg_names(params))
        ps = params if params.strip() else "void"
        lines.append(f"{ret} dawn_{s}({ps});")
        if s in vkw:
            lines.append(f"{ret} vkw_{s}({ps});")
        call_ret = "" if ret == "void" else "return "
        lines.append(f"{ret} {s}({ps}) {{")
        if s in vkw:
            lines.append(f"  if (aurora_wgpu_vk) {{ {call_ret}vkw_{s}({args}); {'return; ' if ret == 'void' else ''}}}")
        else:
            lines.append(f'  if (aurora_wgpu_vk) aurora_wgpu_missing("{s}");')
        lines.append(f"  {call_ret}dawn_{s}({args});")
        lines.append("}")
    lines.append("}  // extern \"C\"")
    with open(os.path.join(OUT, "wgpu_dispatch.cpp"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    missing_vkw = sorted(vkw - set(dawn))
    print(f"{len(dawn)} Dawn functions, {len(vkw)} in vk_webgpu, {len(set(dawn) & vkw)} shared")
    if missing_vkw:
        print("vk_webgpu functions Dawn does not export:", " ".join(missing_vkw))


if __name__ == "__main__":
    main()
